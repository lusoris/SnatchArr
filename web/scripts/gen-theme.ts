// Emits src/lib/theme.css from sveltesentio's oklch tokens and the dashboard preset, so
// the stylesheet is static (CSP hash mode, no runtime {@html}).
import { writeFileSync } from 'node:fs';
import { presetCss, presetDashboard } from '@sveltesentio/ui/presets';
import { darkTokens, lightTokens, themeCss } from '@sveltesentio/ui/tokens';

const banner = `/* SPDX-FileCopyrightText: 2026 lusoris <lusoris@pm.me> */\n/* SPDX-License-Identifier: EUPL-1.2 */\n/* Generated by scripts/gen-theme.ts - do not edit. */\n`;
// The stock --color-input (1.26:1 light, 1.31:1 dark) is the only boundary of a text input, so it
// needs 3:1 (WCAG 2.2 SC 1.4.11) against the page, card and popover colours it sits on (#342).
// Lightness is the minimum shift that clears 3:1 with margin: light 3.36:1, dark 4.18:1 on the
// card. --color-border stays subtle: it only draws dividers and card edges.
// web/src/lib/theme-contrast.test.ts reads the generated file and fails below 3:1.
const light = { ...lightTokens, input: 'oklch(0.64 0 0)' };
const dark = { ...darkTokens, input: 'oklch(0.58 0 0)' };
const css = `${banner}${themeCss({ light, dark })}\n${presetCss(presetDashboard, ':root')}\n`;
writeFileSync(new URL('../src/lib/theme.css', import.meta.url), css);
console.warn('wrote src/lib/theme.css');
