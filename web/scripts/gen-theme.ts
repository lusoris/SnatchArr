// Emits src/lib/theme.css from sveltesentio's palette A (presetSnatchArr) and dashboard preset,
// so the stylesheet is static (CSP hash mode, no runtime {@html}).
import { writeFileSync } from 'node:fs';
import { paletteCss, presetCss, presetDashboard, presetSnatchArr } from '@sveltesentio/ui/presets';

const banner = `/* SPDX-FileCopyrightText: 2026 lusoris <lusoris@pm.me> */\n/* SPDX-License-Identifier: EUPL-1.2 */\n/* Generated by scripts/gen-theme.ts - do not edit. */\n`;

// Stock presetSnatchArr input (oklch(0.60 0.04 285)) clears 3:1 (WCAG 2.2 SC 1.4.11)
// against page, card and popover in both themes (light: 3.79:1 on bg, 3.98:1 on card/popover;
// dark: 5.02:1 on bg, 4.58:1 on card/popover), so no override is needed (#342).
//
// Semantic warning token (SnatchArr-local, #417, #418): amber hue ~80.
// Clears 3:1 against card, background, and muted track in both themes (light: 4.91:1 card,
// 4.68:1 bg, 4.11:1 muted; dark: 8.05:1 card, 8.82:1 bg, 6.94:1 muted). Clears 4.5:1
// for text against card and background, so it can be used for text and border.
const warningLight = 'oklch(0.55 0.16 80)';
const warningDark = 'oklch(0.75 0.16 80)';

const palette = paletteCss(presetSnatchArr)
	.replace(/(:root\s*\{[^}]*)(\})/, `$1\t--color-warning: ${warningLight};\n$2`)
	.replace(/(\.dark\s*\{[^}]*)(\})/, `$1\t--color-warning: ${warningDark};\n$2`);

// presetDashboard non-colour variables: radius, density, font sizes for @sveltesentio/ui
// components (DataTable, CommandPalette). Emits zero --color-* variables.
const css = `${banner}${palette}\n${presetCss(presetDashboard, ':root')}\n`;
writeFileSync(new URL('../src/lib/theme.css', import.meta.url), css);
console.warn('wrote src/lib/theme.css');
