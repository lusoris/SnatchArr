package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"

	"gopkg.in/yaml.v3"
)

// GenerateCode parses OpenAPI YAML and emits Go source code defining moduleops.ByOperation.
func GenerateCode(src []byte) ([]byte, error) {
	opsMap, err := extractModuleOps(src)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/moduleroutes. DO NOT EDIT.\n")
	buf.WriteString("\n")
	buf.WriteString("package moduleops\n\n")
	if len(opsMap) == 0 {
		buf.WriteString("var ByOperation = map[string]string{}\n")
	} else {
		buf.WriteString("var ByOperation = map[string]string{\n")
		for _, opID := range slices.Sorted(maps.Keys(opsMap)) {
			fmt.Fprintf(&buf, "\t%q: %q,\n", opID, opsMap[opID])
		}
		buf.WriteString("}\n")
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return formatted, nil
}

func extractModuleOps(src []byte) (map[string]string, error) {
	var spec rawOpenAPISpec
	if err := yaml.Unmarshal(src, &spec); err != nil {
		return nil, fmt.Errorf("unmarshal openapi yaml: %w", err)
	}
	opsMap := make(map[string]string)
	for _, pathItem := range spec.Paths {
		if err := processPathOps(pathItem, opsMap); err != nil {
			return nil, err
		}
	}
	return opsMap, nil
}

func processPathOps(pathItem map[string]any, opsMap map[string]string) error {
	for _, method := range httpMethods {
		rawOp, ok := pathItem[method]
		if !ok {
			continue
		}
		opMap, ok := rawOp.(map[string]any)
		if !ok {
			continue
		}
		if err := recordModuleOp(opMap, opsMap); err != nil {
			return err
		}
	}
	return nil
}

func recordModuleOp(opMap map[string]any, opsMap map[string]string) error {
	rawModule, hasModule := opMap["x-module"]
	if !hasModule {
		return nil
	}
	modStr, ok := rawModule.(string)
	if !ok || modStr == "" {
		return errors.New("operation has invalid x-module: must be non-empty string")
	}
	opID, ok := opMap["operationId"].(string)
	if !ok || opID == "" {
		return fmt.Errorf("operation with x-module %q missing operationId", modStr)
	}
	opsMap[opID] = modStr
	return nil
}

func executeGen(inPath, outPath string) (int, error) {
	cleanIn := filepath.Clean(inPath)
	// #nosec G304 G703 -- path provided via CLI flag
	src, err := os.ReadFile(cleanIn)
	if err != nil {
		return 1, fmt.Errorf("read %s: %w", cleanIn, err)
	}
	outBytes, err := GenerateCode(src)
	if err != nil {
		return 1, fmt.Errorf("generate code: %w", err)
	}
	cleanOut := filepath.Clean(outPath)
	if err := os.MkdirAll(filepath.Dir(cleanOut), 0o750); err != nil {
		return 1, fmt.Errorf("mkdir %s: %w", filepath.Dir(cleanOut), err)
	}
	// #nosec G304 G703 -- path provided via CLI flag
	if err := os.WriteFile(cleanOut, outBytes, 0o600); err != nil {
		return 1, fmt.Errorf("write %s: %w", cleanOut, err)
	}
	return 0, nil
}
