// Class identifies the lifecycle and mutation safety tier of a configuration setting.
type Class string

// Setting classes.
const (
	ClassBootstrap Class = "bootstrap"
	ClassRuntime   Class = "runtime"
	ClassSecret    Class = "secret"
)

// Apply specifies when a configuration change takes effect.
type Apply string

// Setting apply modes.
const (
	ApplyRestart Apply = "restart"
	ApplyLive    Apply = "live"
)

// Setting describes a configuration setting, its environment variable binding,
// class, data type, default value, and apply behavior.
type Setting struct {
	Key     string
	Env     string
	Class   Class
	Type    string
	Default string
	Apply   Apply
}

// workerOnly lists non-server variables (worker credentials, fakeworker tokens, test fixtures,
// and MCP stdio client options) excluded from the API registry.
